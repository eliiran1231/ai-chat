// Node's own experimental `localStorage` global takes precedence over anything
// jsdom would otherwise provide, but it only works when the process is started
// with `--localstorage-file`, which the test runner doesn't do. Replace it with
// a plain in-memory implementation so code under test can use `localStorage`
// the same way it does in a real browser.
class MemoryStorage implements Storage {
  private readonly store = new Map<string, string>();

  get length(): number {
    return this.store.size;
  }

  clear(): void {
    this.store.clear();
  }

  getItem(key: string): string | null {
    return this.store.has(key) ? this.store.get(key)! : null;
  }

  key(index: number): string | null {
    return [...this.store.keys()][index] ?? null;
  }

  removeItem(key: string): void {
    this.store.delete(key);
  }

  setItem(key: string, value: string): void {
    this.store.set(key, String(value));
  }
}

globalThis.localStorage = new MemoryStorage();
globalThis.sessionStorage = new MemoryStorage();
